# ------------------------------------------------------------
# 3. Calculate overall business accuracy
# ------------------------------------------------------------

def overall_business_accuracy(metrics):

    required = [
        "Category Accuracy %",
        "Sentiment Accuracy %",
        "Priority Accuracy %",
        "Action Accuracy %"
    ]

    # Check required metrics exist
    missing = [
        x for x in required
        if x not in metrics
    ]

    if missing:
        print(
            "Missing metrics:",
            missing
        )
        return 0

    return sum(
        metrics[x]
        for x in required
    ) / len(required)



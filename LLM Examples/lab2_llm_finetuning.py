def extract_json(text):

    try:

        # First try direct JSON
        return json.loads(text)

    except:

        pass


    try:

        # Remove markdown fences
        cleaned = text.replace(
            "```json", ""
        ).replace(
            "```", ""
        ).strip()

        return json.loads(cleaned)

    except:

        pass


    try:

        # Find first JSON-looking object
        match = re.search(
            r'\{.*\}',
            text,
            re.DOTALL
        )

        if match:

            return json.loads(
                match.group()
            )

    except:

        pass


    return None

REQUIRED_FIELDS = [
    "category",
    "sentiment",
    "priority",
    "action"
]


def evaluate_model(results):

    total = len(results)
    valid_json = 0
    schema_correct = 0
    category_correct = 0
    sentiment_correct = 0
    priority_correct = 0
    action_correct = 0
    exact_match = 0
    latencies = []


    for item in results:

        latencies.append(
            item["latency"]
        )

        parsed = extract_json(
            item["output"]
        )

        if parsed is None:
            continue


        valid_json += 1


        if all(
            field in parsed
            for field in REQUIRED_FIELDS
        ):
            schema_correct += 1


        category_ok = (
            parsed.get("category")
            == item["expected_category"]
        )

        sentiment_ok = (
            parsed.get("sentiment")
            == item["expected_sentiment"]
        )

        priority_ok = (
            parsed.get("priority")
            == item["expected_priority"]
        )

        action_ok = (
            parsed.get("action")
            == item["expected_action"]
        )


        category_correct += category_ok

        sentiment_correct += sentiment_ok

        priority_correct += priority_ok

        action_correct += action_ok


        if (
            category_ok
            and sentiment_ok
            and priority_ok
            and action_ok
        ):
            exact_match += 1


    return {

        "JSON Validity %":
            100 * valid_json / total,

        "Schema Compliance %":
            100 * schema_correct / total,

        "Category Accuracy %":
            100 * category_correct / total,

        "Sentiment Accuracy %":
            100 * sentiment_correct / total,

        "Priority Accuracy %":
            100 * priority_correct / total,

        "Action Accuracy %":
            100 * action_correct / total,

        "Exact Record Accuracy %":
            100 * exact_match / total,

        "Avg Latency (sec)":
            sum(latencies) / len(latencies)
    }

